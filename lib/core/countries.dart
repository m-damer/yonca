/// Dial codes of all countries, longest first so "+971" is tried before "+97" and "+1242" before "+1".
final List<String> kDialCodes = (kCountries.map((c) => c.code).toSet().toList()..sort((a, b) => b.length != a.length ? b.length.compareTo(a.length) : a.compareTo(b)));

/// The first country that uses [code], or null.
Country? countryForCode(String code) {
  for (final c in kCountries) {
    if (c.code == code) return c;
  }
  return null;
}
